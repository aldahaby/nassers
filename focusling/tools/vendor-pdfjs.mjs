// Builds vendor/pdfjs/pdfjs.web.js: Mozilla PDF.js (pdfjs-dist, legacy build for
// older iOS Safari) in a form Metro can bundle for the web app.
// - The worker runs on the main thread (globalThis.pdfjsWorker), so no separate
//   worker file has to be served — works in the normal web build and the
//   single-file preview alike. Syllabi are small; this costs little.
// - import.meta.url and dynamic import() (Node/WASM-only paths) are removed:
//   Metro wraps modules in functions, where import.meta is a syntax error.
// Re-run after upgrading pdfjs-dist:  node tools/vendor-pdfjs.mjs
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const version = JSON.parse(readFileSync(require.resolve('pdfjs-dist/package.json'), 'utf8')).version;
const out = new URL('../vendor/pdfjs/pdfjs.web.js', import.meta.url).pathname;

const entry = `
import * as worker from 'pdfjs-dist/legacy/build/pdf.worker.mjs';
import { getDocument, GlobalWorkerOptions, OPS, version } from 'pdfjs-dist/legacy/build/pdf.mjs';
globalThis.pdfjsWorker = worker;
export { getDocument, GlobalWorkerOptions, OPS, version };
`;

const result = await build({
  stdin: { contents: entry, resolveDir: process.cwd(), loader: 'js' },
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['safari15'],
  minify: true,
  write: false,
  legalComments: 'none',
  define: { 'import.meta.url': '""' },
  logLevel: 'warning',
});

let code = result.outputFiles[0].text;
// Dynamic imports (worker script, WASM image decoders, Node helpers) are never reached here.
// esbuild turns import(x) into Promise.resolve().then(()=>__toESM(require(x))) in CJS; Metro
// rejects non-literal requires in app code, so route them to a rejecting stub.
code = code.replace(/\brequire\(/g, '__pdfjsNoRequire(');
// import(x) with a variable path (not the "import(\"…\")" inside a template string, which is data).
code = code.replace(/\bimport\((?!")/g, '__pdfjsNoImport(');
const header = `/* PDF.js ${version} (Mozilla, Apache-2.0) — generated by tools/vendor-pdfjs.mjs; do not edit. */
/* eslint-disable */
var __pdfjsNoRequire = function (m) { throw new Error('PDF.js tried to load ' + String(m) + ', which is not bundled for the web app.'); };
var __pdfjsNoImport = function (m) { return Promise.reject(new Error('PDF.js tried to load ' + String(m) + ', which is not bundled for the web app.')); };
`;
writeFileSync(out, header + code);
const left = (code.match(/import\.meta|\bimport\((?!")/g) || []).length;
console.log(`pdfjs ${version} → ${out} (${(code.length / 1024).toFixed(0)} KB); import.meta / dynamic import left: ${left}`);
if (left) process.exit(1);
